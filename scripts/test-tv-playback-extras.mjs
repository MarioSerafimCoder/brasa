import assert from "node:assert/strict";
import { trustedChapterMarkers } from "../server/playback-markers.mjs";
import { thumbnailBucket, createTvThumbnails } from "../server/tv-thumbnails.mjs";
const chapter = (title, start, end) => ({ tags: { title }, start_time: start, end_time: end });
assert.deepEqual(trustedChapterMarkers([chapter("Chapter 1", 0, 90), chapter("Opening scene", 90, 200)], 1200), []);
const markers = trustedChapterMarkers([chapter("Opening", 60, 150), chapter("Credits", 1100, 1180), chapter("Post credits", 1180, 1200)], 1200);
assert.equal(markers.length, 2); assert.equal(markers[0].startMs, 60_000); assert.equal(markers[1].endMs, 1_180_000);
assert.deepEqual(trustedChapterMarkers([chapter("Intro", 700, 790), chapter("Credits", 200, 400), chapter("OP", -1, 50), chapter("ED", 1150, 1300)], 1200), []);
assert.equal(trustedChapterMarkers([chapter("Abertura", 0, 90), chapter("OP", 10, 120)], 1200).length, 1);
assert.equal(thumbnailBucket(39_999, 120_000), 30_000); assert.equal(thumbnailBucket(Infinity, 120_000), null);
assert.equal(thumbnailBucket(999_999, 120_000), 110_000);
let busy = false, generated = 0, release;
const jpeg = Buffer.from([0xff, 0xd8, 0xff, 0xd9]);
const service = createTvThumbnails({ busy: () => busy, extract: async () => { generated++; return jpeg; } });
const input = { file: "test.mp4", revision: "1", positionMs: 20_000, durationMs: 120_000, ffmpeg: "test", allowed: true };
busy = true; assert.equal(await service.get(input), null); assert.equal(generated, 0);
busy = false; assert.equal(await service.get({ ...input, allowed: false }), null);
assert.deepEqual(await service.get(input), jpeg); assert.equal(generated, 1);
busy = true; assert.deepEqual(await service.get({ ...input, allowed: false }), jpeg); assert.equal(generated, 1);
busy = false; await service.get({ ...input, revision: "2" }); assert.equal(generated, 2);
const serial = createTvThumbnails({ extract: () => new Promise(resolve => { release = () => resolve(jpeg); }) });
const first = serial.get(input); assert.equal(await serial.get({ ...input, positionMs: 30_000 }), null); release(); await first;
assert.equal(await createTvThumbnails({ extract: async () => Buffer.alloc(200_000) }).get(input), null);
assert.equal(await service.get({ ...input, revision: "3", signal: { aborted: true } }), null);
console.log("Extras TV: capítulos explícitos, pós-créditos preservados, miniaturas limitadas, cache por revisão e prioridade da reprodução aprovados.");
